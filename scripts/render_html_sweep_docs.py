#!/usr/bin/env python
"""Write the HTML sweep verdicts into docs/source_registration_list.md.

The doc is the public record of which sources were measured and what happened,
so it is generated from the result files rather than retyped -- a table typed by
hand drifts from the run it claims to describe.

Usage:
    uv run python scripts/render_html_sweep_docs.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "source_registration_list.md"
RESULTS = ROOT / "reports" / "html_scraper_test_results.json"
PERSIST = ROOT / "reports" / "html_scraper_persist_results.json"

START = "<!-- html-sweep:start -->"
END = "<!-- html-sweep:end -->"

HEADINGS = {
    "OK": "Verified: postings stored",
    "PARSE_FAIL": "Fetched pages but no posting survived the quality gate",
    "NO_LINKS": "Listing has no job links over plain HTTP",
    "BLOCKED": "Refused the request (403 / WAF)",
    "DNS_FAIL": "Host does not resolve",
    "TIMEOUT": "Exceeded the test timeout",
    "ERROR": "Unexpected error",
    "NO_CONFIG": "No site config",
    "EMPTY": "Listing request failed (server error, TLS, timeout)",
}


def load(path: Path) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else []


def render(results: list[dict], persisted: dict[str, dict]) -> str:
    lines = [
        START,
        "",
        "## F. HTML sources measured 2026-10-21",
        "",
        "Every site config shipped with the generic HTML framework was run once,",
        "then the ones that produced postings were run with persistence on. The",
        "table is generated by `scripts/render_html_sweep_docs.py` from",
        "`reports/html_scraper_test_results.json`; it is not typed by hand.",
        "",
        "A record only counts as a posting after",
        "`validation/html_scraper_quality.py` accepts it. That gate was added",
        "because the first sweep counted navigation links as successes: 499 of",
        "536 stored rows were the site's own menu, news articles or bot-challenge",
        "pages, and were deleted before anything was published.",
        "",
    ]

    counts: dict[str, int] = {}
    for row in results:
        counts[row["status"]] = counts.get(row["status"], 0) + 1
    summary = " | ".join(f"{k}: {v}" for k, v in counts.items())
    lines.append(f"**{len(results)} configs tested** -- {summary}")
    lines.append("")

    for status in (
        "OK",
        "PARSE_FAIL",
        "NO_LINKS",
        "BLOCKED",
        "EMPTY",
        "TIMEOUT",
        "DNS_FAIL",
        "ERROR",
        "NO_CONFIG",
    ):
        rows = [r for r in results if r["status"] == status]
        if not rows:
            continue
        lines.append(f"### {HEADINGS.get(status, status)} ({len(rows)})")
        lines.append("")
        if status == "OK":
            lines.append("| Source | Parsed in test | Row(s) stored |")
            lines.append("| --- | --- | --- |")
            for row in sorted(rows, key=lambda r: r["code"]):
                stored = persisted.get(row["code"], {}).get("rows_after", 0)
                lines.append(f"| `{row['code']}` | {row['parsed']} | {stored} |")
        else:
            lines.append("| Source | Measured reason |")
            lines.append("| --- | --- |")
            for row in sorted(rows, key=lambda r: r["code"]):
                reason = (row.get("detail") or status).replace("|", "/")
                lines.append(f"| `{row['code']}` | {reason[:140]} |")
        lines.append("")

    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    results = load(RESULTS)
    if not results:
        print(f"no results at {RESULTS}")
        return 1
    persisted = {r["code"]: r for r in load(PERSIST)}

    block = render(results, persisted)
    text = DOC.read_text(encoding="utf-8")
    if START in text and END in text:
        head, _, rest = text.partition(START)
        _, _, tail = rest.partition(END)
        text = head + block + tail
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    DOC.write_text(text, encoding="utf-8")
    print(f"wrote {DOC} ({len(results)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
